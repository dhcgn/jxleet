// Command gen produces flags_generated.go and a JSON snapshot from the output
// of `cjxl --help -v -v -v -v`. It is invoked via `go generate` from the flags
// package. With cjxl on PATH no arguments are needed; pass -input to parse a
// captured help file instead (used for tests and offline development).
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
	"text/template"

	jxlflags "github.com/dhcgn/jxleet/internal/cjxl/flags"
)

func main() {
	var (
		cjxlPath = flag.String("cjxl", "cjxl", "path to the cjxl binary")
		input    = flag.String("input", "", "read help text from this file instead of running cjxl")
		version  = flag.String("version", "", "override the detected cjxl version")
		out      = flag.String("out", "flags_generated.go", "output Go file")
		snapshot = flag.String("snapshot", "", "directory to write the JSON snapshot into (optional)")
	)
	flag.Parse()

	helpText, ver, err := gather(*cjxlPath, *input, *version)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}

	parsed, err := jxlflags.Parse(strings.NewReader(helpText))
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen: parse:", err)
		os.Exit(1)
	}
	if len(parsed) == 0 {
		fmt.Fprintln(os.Stderr, "gen: parsed 0 flags — refusing to write empty output")
		os.Exit(1)
	}

	if err := writeGo(*out, ver, parsed); err != nil {
		fmt.Fprintln(os.Stderr, "gen: write go:", err)
		os.Exit(1)
	}
	fmt.Printf("gen: wrote %s (%d flags, cjxl %s)\n", *out, len(parsed), ver)

	if *snapshot != "" {
		if err := writeSnapshot(*snapshot, ver, parsed); err != nil {
			fmt.Fprintln(os.Stderr, "gen: write snapshot:", err)
			os.Exit(1)
		}
	}
}

func gather(cjxlPath, input, versionOverride string) (help, version string, err error) {
	version = versionOverride
	if input != "" {
		b, readErr := os.ReadFile(input)
		if readErr != nil {
			return "", "", readErr
		}
		if version == "" {
			version = "unknown"
		}
		return string(b), version, nil
	}

	helpBytes, err := exec.Command(cjxlPath, "--help", "-v", "-v", "-v", "-v").Output()
	if err != nil {
		return "", "", fmt.Errorf("run cjxl --help: %w", err)
	}
	if version == "" {
		// `cjxl --version` prints e.g. "cjxl v0.12.0 4128790 [...]".
		verBytes, _ := exec.Command(cjxlPath, "--version").CombinedOutput()
		version = detectVersion(string(verBytes))
	}
	return string(helpBytes), version, nil
}

var versionRe = regexp.MustCompile(`v(\d+\.\d+\.\d+)`)

func detectVersion(s string) string {
	if m := versionRe.FindStringSubmatch(s); m != nil {
		return m[1]
	}
	return "unknown"
}

const tmpl = `// Code generated by internal/cjxl/flags/gen; DO NOT EDIT.
// Source: cjxl --help -v -v -v -v (cjxl {{.Version}}).

package flags

// GeneratedVersion is the cjxl version the committed flag set was generated from.
const GeneratedVersion = {{printf "%q" .Version}}

func generatedFlags() []Flag {
	return []Flag{
{{- range .Flags}}
		{Short: {{printf "%q" .Short}}, Long: {{printf "%q" .Long}}, TakesValue: {{.TakesValue}}, ValueSpec: {{printf "%q" .ValueSpec}}, Section: {{printf "%q" .Section}}, Description: {{printf "%q" .Description}}},
{{- end}}
	}
}
`

func writeGo(path, version string, parsed []jxlflags.Flag) error {
	t := template.Must(template.New("gen").Parse(tmpl))
	var buf bytes.Buffer
	if err := t.Execute(&buf, struct {
		Version string
		Flags   []jxlflags.Flag
	}{version, parsed}); err != nil {
		return err
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("gofmt generated source: %w", err)
	}
	return os.WriteFile(path, formatted, 0o644)
}

func writeSnapshot(dir, version string, parsed []jxlflags.Flag) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	set := jxlflags.NewSet(version, parsed)
	b, err := json.MarshalIndent(set, "", "  ")
	if err != nil {
		return err
	}
	path := filepath.Join(dir, "flags-"+version+".json")
	return os.WriteFile(path, b, 0o644)
}
